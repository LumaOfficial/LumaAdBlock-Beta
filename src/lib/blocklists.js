export function rulesForLists(enabledIds) {
  const enabled = new Set(enabledIds)
  return FILTER_LISTS.filter((list) => enabled.has(list.id))
}

export function countRules(list) {
  return list.rules.filter((rule) => !rule.startsWith('!')).length
}

export function countCosmetic(list) {
  return list.rules.filter((rule) => rule.includes('##') || rule.includes('#@#')).length
}

