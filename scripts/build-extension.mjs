#!/usr/bin/env node
/**
 * Builds the Luma browser extension into extension/:
 *   manifest.json      generated from the bundled lists
 *   rules/<list>.json  declarativeNetRequest rulesets, one per filter list
 *   cosmetic/<list>.css element-hiding stylesheet, one per filter list
 *   icons/             toolbar icons
 *   app/               the dashboard, built from src/
 */
import { execFileSync } from 'node:child_process'
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { deflateSync } from 'node:zlib'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { DEFAULT_LISTS, FILTER_LISTS } from '../src/lib/blocklists.js'
import { compileRules, toDeclarativeNetRequest } from '../src/lib/engine.js'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = path.join(root, 'extension')

function validateRuleset(listId, rules) {
  const seen = new Set()
  for (const rule of rules) {
    if (!Number.isInteger(rule.id) || rule.id < 1) {
      throw new Error(listId + ': rule ids must be positive integers')
    }
    if (seen.has(rule.id)) throw new Error(listId + ': duplicate rule id ' + rule.id)
    seen.add(rule.id)
    if (!rule.action || !rule.action.type) throw new Error(listId + ': rule ' + rule.id + ' has no action')
    if (!rule.condition || (!rule.condition.urlFilter && !rule.condition.regexFilter)) {
      throw new Error(listId + ': rule ' + rule.id + ' has no filter')
    }
  }
  return rules
}

function countHiding(compiled) {
  return new Set(
    compiled.filter((rule) => rule.kind === 'cosmetic' && !rule.exception).map((rule) => rule.selector),
  ).size
}

function cosmeticCss(list, compiled) {
  const generic = []
  for (const rule of compiled) {
    if (rule.kind !== 'cosmetic' || rule.exception) continue
    if (rule.domains.length) {
      throw new Error(
        list.id + ': site-scoped hiding rule "' + rule.raw + '" needs the content-script path',
      )
    }
    generic.push(rule.selector)
  }
  const selectors = [...new Set(generic)]
  if (!selectors.length) return '/* ' + list.name + ': no element hiding rules */\n'
  return (
    '/* ' + list.name + ' — element hiding (generated by scripts/build-extension.mjs) */\n' +
    selectors.join(',\n') +
    ' {\n  display: none !important;\n}\n'
  )
}

const CRC_TABLE = (() => {
  const table = new Int32Array(256)
  for (let n = 0; n < 256; n += 1) {
    let c = n
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1
    table[n] = c
  }
  return table
})()

function crc32(buffer) {
  let crc = -1
  for (const byte of buffer) crc = CRC_TABLE[(crc ^ byte) & 0xff] ^ (crc >>> 8)
  return (crc ^ -1) >>> 0
}

function pngChunk(type, data) {
  const length = Buffer.alloc(4)
  length.writeUInt32BE(data.length)
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data])
  const crc = Buffer.alloc(4)
  crc.writeUInt32BE(crc32(body))
  return Buffer.concat([length, body, crc])
}

/** Renders the Luma mark: an orange ring with a paper-coloured centre. */
function icon(size) {
  const raw = Buffer.alloc(size * (size * 4 + 1))
  const padding = 1
  const outer = size / 2 - padding
  const inner = outer * 0.46
  for (let y = 0; y < size; y += 1) {
    raw[y * (size * 4 + 1)] = 0
    for (let x = 0; x < size; x += 1) {
      const dx = x - size / 2 + 0.5
      const dy = y - size / 2 + 0.5
      const distance = Math.sqrt(dx * dx + dy * dy)
      const index = y * (size * 4 + 1) + 1 + x * 4
      const edge = Math.min(1, Math.max(0, outer - distance))
      const hole = Math.min(1, Math.max(0, distance - inner))
      if (edge <= 0 || hole <= 0) {
        raw[index] = 0
        raw[index + 1] = 0
        raw[index + 2] = 0
        raw[index + 3] = 0
      } else {
        raw[index] = 0xef
        raw[index + 1] = 0x5a
        raw[index + 2] = 0x2b
        raw[index + 3] = Math.round(255 * Math.min(edge, hole))
      }
    }
  }
  const header = Buffer.alloc(13)
  header.writeUInt32BE(size, 0)
  header.writeUInt32BE(size, 4)
  header[8] = 8
  header[9] = 6
  return Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    pngChunk('IHDR', header),
    pngChunk('IDAT', deflateSync(raw, { level: 9 })),
    pngChunk('IEND', Buffer.alloc(0)),
  ])
}

async function main() {
  // Accounts live on the Luma account service, so the packaged dashboard needs
  // to know where it is. Never fall back to a sandbox/preview address.
  const apiUrl = String(process.env.LUMA_API_URL || '').trim()
  if (!/^https:\/\/[^/]+/.test(apiUrl)) {
    throw new Error(
      'Set LUMA_API_URL to the https address of the deployed account service, e.g.\n' +
        '  LUMA_API_URL=https://api.example.com npm run build:extension',
    )
  }
  const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))

  await rm(path.join(out, 'rules'), { recursive: true, force: true })
  await rm(path.join(out, 'cosmetic'), { recursive: true, force: true })
  await rm(path.join(out, 'icons'), { recursive: true, force: true })
  await mkdir(path.join(out, 'rules'), { recursive: true })
  await mkdir(path.join(out, 'cosmetic'), { recursive: true })
  await mkdir(path.join(out, 'icons'), { recursive: true })

  const summary = []
  const rulesets = []
  for (const list of FILTER_LISTS) {
    const compiled = compileRules(list.rules, list.id)
    const rules = validateRuleset(list.id, toDeclarativeNetRequest(compiled))
    await writeFile(path.join(out, 'cosmetic', list.id + '.css'), cosmeticCss(list, compiled))
    // A list with no network rules ships its stylesheet only.
    if (rules.length) {
      await writeFile(path.join(out, 'rules', list.id + '.json'), JSON.stringify(rules, null, 2) + '\n')
      rulesets.push({
        id: list.id,
        enabled: Boolean(DEFAULT_LISTS[list.id]),
        path: 'rules/' + list.id + '.json',
      })
    }
    summary.push({ list: list.name, rules: rules.length, hiding: countHiding(compiled) })
  }

  for (const size of [16, 32, 48, 128]) {
    await writeFile(path.join(out, 'icons', 'icon' + size + '.png'), icon(size))
  }

  const manifest = {
    manifest_version: 3,
    name: 'Luma Ad Blocker',
    version: pkg.version,
    description: pkg.description,
    minimum_chrome_version: '102',
    permissions: ['declarativeNetRequest', 'declarativeNetRequestFeedback', 'storage', 'scripting'],
    host_permissions: ['<all_urls>'],
    background: { service_worker: 'background.js' },
    action: { default_title: 'Luma Ad Blocker' },
    options_ui: { page: 'app/index.html', open_in_tab: true },
    icons: {
      16: 'icons/icon16.png',
      32: 'icons/icon32.png',
      48: 'icons/icon48.png',
      128: 'icons/icon128.png',
    },
    content_scripts: [
      {
        matches: ['<all_urls>'],
        js: ['content.js'],
        run_at: 'document_start',
      },
    ],
    declarative_net_request: { rule_resources: rulesets },
  }
  await writeFile(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n')

  console.log('Extension rules and manifest written:')
  for (const row of summary) {
    console.log(
      '  ' + row.list.padEnd(20) + String(row.rules).padStart(3) + ' network rules · ' +
        row.hiding + ' hiding selectors',
    )
  }

  console.log('Building the dashboard into extension/app …')
  execFileSync(
    process.execPath,
    [
      path.join(root, 'node_modules', 'vite', 'bin', 'vite.js'),
      'build',
      '--base=./',
      '--outDir',
      'extension/app',
      '--emptyOutDir',
    ],
    { cwd: root, stdio: 'inherit', env: { ...process.env, VITE_API_URL: apiUrl } },
  )

  console.log('Done. Load the extension/ folder as an unpacked extension.')
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
