#!/usr/bin/env node
/**
 * Builds the Luma browser extension into extension/:
 *   manifest.json      generated from the bundled lists
 *   rules/<list>.json  declarativeNetRequest rulesets, one per filter list
 *   cosmetic/<list>.css element-hiding stylesheet, one per filter list
 *   icons/             toolbar icons
 *   app/               the dashboard, built from src/
 */
import { execFileSync } from 'node:child_process'
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { DEFAULT_LISTS, FILTER_LISTS } from '../src/lib/blocklists.js'
import { BROWSER_TYPES, compileRules, toDeclarativeNetRequest } from '../src/lib/engine.js'

const BROWSER_TYPE_NAMES = new Set(Object.values(BROWSER_TYPES))

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const out = path.join(root, 'extension')

function validateRuleset(listId, rules) {
  const seen = new Set()
  for (const rule of rules) {
    if (!Number.isInteger(rule.id) || rule.id < 1) {
      throw new Error(listId + ': rule ids must be positive integers')
    }
    if (seen.has(rule.id)) throw new Error(listId + ': duplicate rule id ' + rule.id)
    seen.add(rule.id)
    if (!rule.action || !rule.action.type) throw new Error(listId + ': rule ' + rule.id + ' has no action')
    if (!rule.condition || (!rule.condition.urlFilter && !rule.condition.regexFilter)) {
      throw new Error(listId + ': rule ' + rule.id + ' has no filter')
    }
    // The browser rejects the entire ruleset over one unknown request type,
    // which would turn blocking off without any visible error.
    for (const type of [
      ...(rule.condition.resourceTypes || []),
      ...(rule.condition.excludedResourceTypes || []),
    ]) {
      if (!BROWSER_TYPE_NAMES.has(type)) {
        throw new Error(listId + ': rule ' + rule.id + ' uses an unknown request type "' + type + '"')
      }
    }
    // Test fixtures belong in the lab, never in the shipped package.
    const filter = rule.condition.urlFilter || rule.condition.regexFilter || ''
    if (/\.test(?:[\^/|]|$)/.test(filter)) {
      throw new Error(listId + ': rule ' + rule.id + ' filters a test domain (' + filter + ')')
    }
  }
  return rules
}

function countHiding(compiled) {
  return new Set(
    compiled.filter((rule) => rule.kind === 'cosmetic' && !rule.exception).map((rule) => rule.selector),
  ).size
}

function cosmeticCss(list, compiled) {
  const generic = []
  for (const rule of compiled) {
    if (rule.kind !== 'cosmetic' || rule.exception) continue
    if (rule.domains.length) {
      throw new Error(
        list.id + ': site-scoped hiding rule "' + rule.raw + '" needs the content-script path',
      )
    }
    generic.push(rule.selector)
  }
  const selectors = [...new Set(generic)]
  if (!selectors.length) {
    return { css: '/* ' + list.name + ': no element hiding rules */\n', selectors }
  }
  // One rule per selector: a selector a browser refuses to parse then only
  // loses itself instead of voiding the whole stylesheet.
  const css =
    '/* ' + list.name + ' — element hiding (generated by scripts/build-extension.mjs) */\n' +
    selectors.map((selector) => selector + ' {\n  display: none !important;\n}\n').join('')
  // The content script needs the same list as data: Visual mode draws an
  // outline over each slot before it collapses, which a stylesheet cannot do.
  return { css, selectors }
}

async function main() {
  // Accounts live on the Luma account service, so the packaged dashboard needs
  // to know where it is. Never fall back to a sandbox/preview address.
  const apiUrl = String(process.env.LUMA_API_URL || '').trim()
  if (!/^https:\/\/[^/]+/.test(apiUrl)) {
    console.warn(
      'No LUMA_API_URL set: this package blocks ads but cannot reach an account service.\n' +
        'For a store build set LUMA_API_URL to the https address of the deployed\n' +
        'account service, e.g. LUMA_API_URL=https://api.example.com npm run build:extension',
    )
  }
  const pkg = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'))

  await rm(path.join(out, 'rules'), { recursive: true, force: true })
  await rm(path.join(out, 'cosmetic'), { recursive: true, force: true })
  await rm(path.join(out, 'icons'), { recursive: true, force: true })
  await mkdir(path.join(out, 'rules'), { recursive: true })
  await mkdir(path.join(out, 'cosmetic'), { recursive: true })
  await mkdir(path.join(out, 'icons'), { recursive: true })

  const summary = []
  const rulesets = []
  const selectorMap = {}
  for (const list of FILTER_LISTS) {
    const compiled = compileRules(list.rules, list.id)
    const rules = validateRuleset(list.id, toDeclarativeNetRequest(compiled))
    const cosmetic = cosmeticCss(list, compiled)
    selectorMap[list.id] = cosmetic.selectors
    await writeFile(path.join(out, 'cosmetic', list.id + '.css'), cosmetic.css)
    // A list with no network rules ships its stylesheet only.
    if (rules.length) {
      await writeFile(path.join(out, 'rules', list.id + '.json'), JSON.stringify(rules, null, 2) + '\n')
      rulesets.push({
        id: list.id,
        enabled: Boolean(DEFAULT_LISTS[list.id]),
        path: 'rules/' + list.id + '.json',
      })
    }
    summary.push({ list: list.name, rules: rules.length, hiding: countHiding(compiled) })
  }

  // Same selectors as data, for the content script's Visual mode and counting.
  await writeFile(
    path.join(out, 'cosmetic', 'selectors.json'),
    JSON.stringify(selectorMap, null, 2) + '\n',
  )

  // The designer's mark, cut out on a transparent background.
  for (const size of [16, 32, 48, 128]) {
    await copyFile(
      path.join(root, 'src', 'assets', 'brand', 'icon' + size + '.png'),
      path.join(out, 'icons', 'icon' + size + '.png'),
    )
  }

  // The worker applies these the moment the extension is installed, so ads are
  // hidden before the dashboard has ever been opened.
  await writeFile(
    path.join(out, 'luma-defaults.json'),
    JSON.stringify({ protection: true, lists: DEFAULT_LISTS }, null, 2) + '\n',
  )

  const manifest = {
    manifest_version: 3,
    name: 'Luma Ad Blocker',
    version: pkg.version,
    description: pkg.description,
    author: 'Luma Official',
    minimum_chrome_version: '102',
    permissions: ['alarms', 'contextMenus', 'declarativeNetRequest', 'storage', 'scripting'],
    host_permissions: ['<all_urls>'],
    // The content script reads the same selectors the stylesheets are built
    // from. A packaged file can only be read from a page when it is listed
    // here; without it the read fails and Visual mode hides nothing.
    web_accessible_resources: [
      { resources: ['cosmetic/selectors.json'], matches: ['<all_urls>'] },
    ],
    background: { service_worker: 'background.js' },
    action: {
      default_title: 'Luma Ad Blocker',
      // The compact panel, sized for a popup or an Opera side panel.
      default_popup: 'app/index.html#/panel',
    },
    options_ui: { page: 'app/index.html', open_in_tab: true },
    icons: {
      16: 'icons/icon16.png',
      32: 'icons/icon32.png',
      48: 'icons/icon48.png',
      128: 'icons/icon128.png',
    },
    content_scripts: [
      {
        matches: ['<all_urls>'],
        js: ['content.js'],
        run_at: 'document_start',
      },
      {
        // Player ads come from YouTube itself; youtube.js skips and hides them.
        // all_frames covers embedded players.
        matches: ['*://*.youtube.com/*', '*://*.youtube-nocookie.com/*'],
        js: ['youtube.js'],
        run_at: 'document_start',
        all_frames: true,
      },
      {
        // Click-to-block: outlines an element and hides the one picked. It
        // waits for a message, so an idle page pays nothing for it.
        matches: ['<all_urls>'],
        js: ['picker.js'],
        run_at: 'document_idle',
      },
    ],
    commands: {
      _execute_action: {
        suggested_key: { default: 'Alt+Shift+L' },
        description: 'Open the Luma panel',
      },
      'toggle-protection': {
        suggested_key: { default: 'Alt+Shift+P' },
        description: 'Turn protection on or off',
      },
      'pick-element': {
        suggested_key: { default: 'Alt+Shift+E' },
        description: 'Block an element on this page',
      },
    },
    declarative_net_request: { rule_resources: rulesets },
  }
  await writeFile(path.join(out, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n')

  console.log('Extension rules and manifest written:')
  for (const row of summary) {
    console.log(
      '  ' + row.list.padEnd(20) + String(row.rules).padStart(3) + ' network rules · ' +
        row.hiding + ' hiding selectors',
    )
  }

  console.log('Building the dashboard into extension/app …')
  execFileSync(
    process.execPath,
    [
      path.join(root, 'node_modules', 'vite', 'bin', 'vite.js'),
      'build',
      '--base=./',
      '--outDir',
      'extension/app',
      '--emptyOutDir',
    ],
    {
      cwd: root,
      stdio: 'inherit',
      // Store reviewers must be able to read the code, so the extension build
      // is not minified (see vite.config.js).
      env: { ...process.env, VITE_API_URL: apiUrl, LUMA_EXTENSION: '1' },
    },
  )

  console.log('Done. Load the extension/ folder as an unpacked extension.')
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
